import Foundation

/// 캘린더 이벤트를 **빨간 날짜로 칠할지** 판정한다.
///
/// 예전엔 한국 법정공휴일을 코드로 직접 계산했다(`KoreanHolidayCalculator`). 사용자가 어느
/// 나라에 있든 한국 날짜를 빨갛게 칠했고, 대체공휴일 이후에 새로 생긴 공휴일(2026년 제헌절
/// 부활, 임시공휴일, 선거일)은 코드를 고쳐야만 반영됐다. 이제는 **사용자 기기의 공휴일
/// 캘린더를 읽는다** — 애플이 알아서 갱신해 주므로 우리가 손댈 일이 없다.
///
/// ## 판정 — 세 조건이 모두 맞아야 한다
///
/// 1. **기기 지역**이 아래 `holidayCalendarTitles`에 있는가
/// 2. **캘린더 제목**이 그 지역의 공휴일 캘린더 이름과 정확히 같은가
/// 3. **종일** 이벤트인가
///
/// 제목으로 좁히는 이유: EventKit에 "이건 공휴일 캘린더"라는 공개 플래그가 없다
/// (`EKCalendar.isSubscribedHolidayCalendar`가 존재하지만 비공개 API라 쓸 수 없다).
/// 예전엔 "구독형 + 읽기전용 + 종일"이라는 성질로 추측했는데, 그 조건은 학사일정·사내
/// 휴무일·절기 달력처럼 **사용자가 구독한 다른 캘린더도 그대로 통과**시켰다.
///
/// 제목은 그보다 훨씬 강한 신호다. 애플은 한국 공휴일을 **한국어판 하나로만** 배포한다 —
/// `calendars.icloud.com/holidays/kr_ko.ics`만 존재하고 `kr_en`·`kr_ja`·`kr_zh`는 404다.
/// 그래서 기기 언어가 무엇이든 제목은 항상 "대한민국 공휴일"이고, 구독 캘린더라 사용자가
/// 이름을 바꿀 수도 없다.
///
/// **실패 방향이 안전하다**: 애플이 이름을 바꾸면 빨간날이 안 뜰 뿐, 엉뚱한 날이 빨개지지는
/// 않는다. 조용히 틀리는 것보다 조용히 비는 편이 낫다.
///
/// ## 왜 한국만인가 — 애플 원본 ICS를 받아서 확인한 결과
///
/// 지역마다 담긴 내용이 전혀 다르다. 같은 "공휴일 캘린더"라는 이름을 달고 있어도:
///
/// - **한국**(71건) — 전부 진짜 공휴일. 대체휴일·임시공휴일·선거일·제헌절까지 들어 있다. ✅
/// - **일본**(44건) — 전부 진짜 축일. 振替休日(대체휴일)도 포함. ✅ 켤 수 있다.
/// - **미국**(120건) — 연방공휴일 10일 외에 밸런타인데이·핼러윈·만우절·세금 납부일,
///   심지어 **서머타임 시작/종료일**까지 들어 있다. ❌
/// - **대만**(230건) — 24절기가 전부(입춘·우수·경칩…) 들어 있다. ❌
///
/// 그래서 **내용이 깨끗한 지역만** 목록에 올린다. 지역을 추가하려면 그 나라 ICS를 직접 받아
/// 안 쉬는 날이 섞여 있지 않은지 먼저 확인해야 한다.
///
/// 순수 함수다 — EventKit을 import하지 않는다. 호출부(`EKEvent.showsAsHoliday`)가 값을 꺼내
/// 넘긴다.
enum HolidayEventPolicy {

    /// 지역 → 그 지역 공휴일 캘린더의 제목.
    ///
    /// 값이 `Set`인 건 언어별 판이 여럿인 지역 때문이다 — 일본은 `日本の祝日`(ja)과
    /// `Japan Holidays`(en) 둘 다 존재한다. 한국은 한국어판 하나뿐이라 원소가 하나다.
    private static let holidayCalendarTitles: [String: Set<String>] = [
        "KR": ["대한민국 공휴일"],
    ]

    /// 이 이벤트를 빨간 날짜로 칠할지.
    ///
    /// - Parameters:
    ///   - regionCode: 기기 지역(설정 > 일반 > 언어 및 지역 > 지역). 언어가 아니라 지역인 이유는
    ///     애플이 어느 나라 공휴일 캘린더를 꽂아줄지 정하는 값이 바로 이것이라서다.
    ///     읽지 못하면(`nil`) **끈다** — 켜는 쪽이 기본값이면 엉뚱한 나라에서 빨개진다.
    ///   - calendarTitle: 이벤트가 속한 캘린더의 제목.
    ///   - isAllDay: 종일 이벤트인지.
    static func showsAsHoliday(
        regionCode: String?,
        calendarTitle: String,
        isAllDay: Bool
    ) -> Bool {
        guard isAllDay, let regionCode else { return false }
        return holidayCalendarTitles[regionCode.uppercased()]?.contains(calendarTitle) ?? false
    }
}
